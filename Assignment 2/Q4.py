#WAP to calculate area of triangle and rectangle

h1 = int(input("Enter the height: "))
b1 = int(input("Enter the base: "))
l1 = int(input("Enter the length: "))
b2 = int(input("Enter the breadth: "))

area_triangle = 1/2 *b1 * h1
area_rectangle = l1 * b2

print('Area of triangle is: ', area_triangle)
print('Area of rectangle is: ', area_rectangle)